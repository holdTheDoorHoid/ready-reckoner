/**
 * The mock catalogue: free actions and purchases with specs, what to look for and avoid, and price
 * bands. Placeholder content in the shape `content/items/*.toml` will have; prices are
 * illustrative and every citation is a `mock_*` id. No brands, no dosing, and firearms appear only
 * as the one permitted free action (docs/CONTENT_STANDARDS.md §5).
 */
import type { BucketId, HazardId, Item, TierId } from '../types';

const RETRIEVED = '2026-09-25';

interface Def {
  id: string;
  name: string;
  category: string;
  unit: string;
  buckets: BucketId[];
  tier: TierId;
  spec: string;
  look_for: string[];
  avoid: string[];
  price?: [number, number, string, string?];
  life_safety?: boolean;
  rare_catastrophic?: boolean;
  rotate?: number;
  check?: number;
  citations: string[];
  extras?: HazardId[];
  kcal?: number;
  litres?: number;
}

function item(d: Def): Item {
  const free = d.price === undefined;
  const [low, high, per, note] = d.price ?? [0, 0, 'once'];
  const out: Item = {
    id: d.id,
    name: d.name,
    category: d.category,
    unit: d.unit,
    buckets: d.buckets,
    tier: free ? 'now' : d.tier,
    free,
    life_safety: d.life_safety ?? false,
    rare_catastrophic: d.rare_catastrophic ?? false,
    spec: d.spec,
    look_for: d.look_for,
    avoid: d.avoid,
    price_band_usd: note === undefined ? { low, high, per } : { low, high, per, note },
    quantity_rule: free ? 'once' : `mock_${d.id}`,
    citations: d.citations,
    hazard_extras: d.extras ?? [],
  };
  if (!free) out.retrieved = RETRIEVED;
  if (d.rotate !== undefined || d.check !== undefined) {
    out.maintenance = {};
    if (d.rotate !== undefined) out.maintenance.rotate_months = d.rotate;
    if (d.check !== undefined) out.maintenance.check_months = d.check;
  }
  if (d.kcal !== undefined) out.energy_kcal_per_unit = d.kcal;
  if (d.litres !== undefined) out.volume_l_per_unit = d.litres;
  return out;
}

